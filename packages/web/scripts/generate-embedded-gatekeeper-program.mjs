#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const spacesRoot = path.resolve(__dirname, '..', 'server', 'lib', 'spaces');
const sourcePath = path.join(spacesRoot, 'gatekeeper-program.cjs');
const outputPath = path.join(spacesRoot, 'gatekeeper-program-embedded.generated.js');

if (!fs.existsSync(sourcePath)) {
  throw new Error(`Missing gatekeeper program: ${sourcePath}`);
}

const content = `// Generated by packages/web/scripts/generate-embedded-gatekeeper-program.mjs.
// Do not edit by hand.

import program from "./gatekeeper-program.cjs" with { type: "text" };

export const embeddedGatekeeperProgram = program;
`;

fs.writeFileSync(outputPath, content);
console.log(`Generated ${outputPath} with the embedded gatekeeper program.`);
